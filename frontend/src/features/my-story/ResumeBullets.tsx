import { useState, useCallback } from 'react';

interface ResumeBulletsProps {
  bullets: string[] | null;
  narrativeInsight: string | null;
}

function CopyButton({ text }: { text: string }) {
  const [copied, setCopied] = useState(false);

  const handleCopy = useCallback(async () => {
    try {
      await navigator.clipboard.writeText(text);
      setCopied(true);
      setTimeout(() => setCopied(false), 2000);
    } catch {
      // Clipboard not available — silently ignore
    }
  }, [text]);

  return (
    <button
      type="button"
      onClick={() => { void handleCopy(); }}
      className={`flex-shrink-0 p-1.5 rounded transition-colors ${
        copied
          ? 'text-accent bg-accent/10'
          : 'text-muted hover:text-on-surface hover:bg-surface-container'
      }`}
      aria-label={copied ? 'Copied!' : 'Copy to clipboard'}
      title={copied ? 'Copied!' : 'Copy bullet'}
    >
      {copied ? (
        /* Check icon */
        <svg className="w-3.5 h-3.5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2.5} aria-hidden="true">
          <path strokeLinecap="round" strokeLinejoin="round" d="M4.5 12.75l6 6 9-13.5" />
        </svg>
      ) : (
        /* Clipboard icon */
        <svg className="w-3.5 h-3.5" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth={2} aria-hidden="true">
          <path strokeLinecap="round" strokeLinejoin="round" d="M15.666 3.888A2.25 2.25 0 0013.5 2.25h-3c-1.03 0-1.9.693-2.166 1.638m7.332 0c.055.194.084.4.084.612v0a.75.75 0 01-.75.75H9a.75.75 0 01-.75-.75v0c0-.212.03-.418.084-.612m7.332 0c.646.049 1.288.11 1.927.184 1.1.128 1.907 1.077 1.907 2.185V19.5a2.25 2.25 0 01-2.25 2.25H6.75A2.25 2.25 0 014.5 19.5V6.257c0-1.108.806-2.057 1.907-2.185a48.208 48.208 0 011.927-.184" />
        </svg>
      )}
    </button>
  );
}

export function ResumeBullets({ bullets, narrativeInsight }: ResumeBulletsProps) {
  if (!bullets || bullets.length === 0) return null;

  return (
    <section
      className="flex flex-col gap-4 animate-fade-up"
      style={{ animationDelay: '200ms' }}
      aria-label="Career highlights"
    >
      <div>
        <h2 className="font-serif text-[1.0625rem] text-on-surface font-normal">
          Career Highlights
        </h2>
        <p className="text-small text-muted mt-0.5">
          AI-generated from your work history — copy and paste into your brag doc or review
        </p>
      </div>

      <ul className="flex flex-col gap-3" role="list">
        {bullets.map((bullet, i) => (
          <li
            key={i}
            className="flex items-start gap-3 bg-surface-lowest rounded-sm p-4 border-l-2 border-l-accent animate-fade-up"
            style={{ animationDelay: `${(i + 5) * 40}ms` }}
          >
            {/* Bullet dot */}
            <span className="flex-shrink-0 mt-[0.4rem] w-1.5 h-1.5 rounded-full bg-accent/60" aria-hidden="true" />
            <p className="flex-1 text-body text-on-surface leading-relaxed">{bullet}</p>
            <CopyButton text={bullet} />
          </li>
        ))}
      </ul>

      {/* AI attribution footer */}
      <div className="flex items-center gap-1.5 pt-1">
        <svg
          className="w-3 h-3 text-muted flex-shrink-0"
          viewBox="0 0 24 24"
          fill="none"
          stroke="currentColor"
          strokeWidth={2}
          aria-hidden="true"
        >
          <path strokeLinecap="round" strokeLinejoin="round" d="M9.813 15.904L9 18.75l-.813-2.846a4.5 4.5 0 00-3.09-3.09L2.25 12l2.846-.813a4.5 4.5 0 003.09-3.09L9 5.25l.813 2.846a4.5 4.5 0 003.09 3.09L15.75 12l-2.846.813a4.5 4.5 0 00-3.09 3.09z" />
        </svg>
        <span className="text-xs text-muted">
          Generated by AI · Review before sharing · Based on {narrativeInsight ? 'your narrative and ' : ''}your commitment history
        </span>
      </div>
    </section>
  );
}
